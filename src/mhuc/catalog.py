"""What MH4U already has of each source game's content, from data/catalog (facts from the wiki).

Two rows are the same monster or locale when they cite the same wiki page (`page_source`), which also catches
renames (the wiki's MHGU "Dunes" is MH4U's "Old Desert"). This says which converted quests would need no
new monster or map (docs/design/quest-conversion.md); it is not a statement that the two games' versions are
the same (that is the open "monster versions" decision).
"""
from __future__ import annotations

import csv
import os

SOURCES = ("MH3U", "MHGU")
TARGET = "MH4U"


def read_table(path: str) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def overlap(rows: list[dict], key: str, kind_field: str) -> dict:
    """For each source game: (rows MH4U has, rows it lacks), each a sorted list of (name, kind, MH4U name)."""
    target = {r["page_source"]: r[key] for r in rows if r["game"] == TARGET}
    out = {}
    for game in SOURCES:
        have, lack = [], []
        for r in rows:
            if r["game"] != game:
                continue
            item = (r[key], r[kind_field], target.get(r["page_source"], ""))
            (have if r["page_source"] in target else lack).append(item)
        out[game] = (sorted(have), sorted(lack))
    return out


def _names(items: list[tuple[str, str, str]]) -> str:
    return ", ".join(n if not t or t == n else f"{n} (MH4U: {t})" for n, _, t in items) or "none"


def render(catalog_dir: str) -> str:
    monsters = overlap(read_table(os.path.join(catalog_dir, "monsters.csv")), "monster", "size")
    maps = overlap(read_table(os.path.join(catalog_dir, "maps.csv")), "locale", "kind")
    lines = [
        "# What MH4U already has",
        "",
        "Generated by `mhuc catalog overlap` from [monsters.csv](monsters.csv) and [maps.csv](maps.csv); "
        "don't edit by hand. Two rows match when they cite the same wiki page. A match means MH4U has a "
        "monster or locale of that name, not that its version is the source game's (the monster-versions "
        "decision is open); it shows which converted quests could run without a new monster or map.",
        "",
        "| Source | Large monsters MH4U has | Large monsters to add | Small monsters MH4U has | "
        "Small monsters to add | Locales MH4U has | Locales to add |",
        "|---|---|---|---|---|---|---|",
    ]
    for game in SOURCES:
        have, lack = monsters[game]
        mh, ml = maps[game]
        cells = [sum(1 for x in have if x[1] == "large"), sum(1 for x in lack if x[1] == "large"),
                 sum(1 for x in have if x[1] == "small"), sum(1 for x in lack if x[1] == "small"),
                 sum(1 for x in mh if x[1] == "locale"), sum(1 for x in ml if x[1] == "locale")]
        lines.append(f"| {game} | " + " | ".join(str(c) for c in cells) + " |")
    for game in SOURCES:
        have, lack = monsters[game]
        mh, ml = maps[game]
        lines += ["", f"## {game}", "",
                  f"- **Large monsters MH4U has:** {_names([x for x in have if x[1] == 'large'])}.",
                  f"- **Large monsters to add:** {_names([x for x in lack if x[1] == 'large'])}.",
                  f"- **Small monsters MH4U has:** {_names([x for x in have if x[1] == 'small'])}.",
                  f"- **Small monsters to add:** {_names([x for x in lack if x[1] == 'small'])}.",
                  f"- **Locales and special locales MH4U has:** {_names([x for x in mh if x[1] != 'settlement'])}.",
                  f"- **Locales and special locales to add:** {_names([x for x in ml if x[1] != 'settlement'])}."]
    return "\n".join(lines) + "\n"
