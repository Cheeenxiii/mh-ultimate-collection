#!/usr/bin/env python3
"""Check the ported monsters' generated motion table, mods/monster_motions/src/motions.h.

The header is generated by `reference/monster_motions.py table` from R1's comparison: one
table per ported monster id, each entry saying which source game's animation the port starts
where MH4U's handler asks for an MH4U motion number. This tool checks that the checked-in
header is the one the generator writes and that it agrees with R1's recorded counts.

Checked without the player's own dumps:

- the header carries the generator's marker and one table per monster in data/ids/registry.csv,
  in id order, with the tables' ids and counts;
- each table's entries are sorted, unique, and hold action and motion numbers in range; its
  left-out ids (category 7's computed index) are sorted, unique, in category 7, and are not
  entries too; an empty table is NULL with a count of 0;
- every action id both handlers start a constant motion for is accounted for: entries +
  left-out ids + the ids that start the same index in both games = R1's compared count, and
  compared + not compared = common;
- the counts equal R1's last result (docs/checks.md#monster-actions, 2026-11-24). A rerun that
  changes them updates R1_COUNTS here and the docs.

With the player's own dumps, pass the same inputs as the generator; the header must then be
exactly what it writes (the check `tools/check_ids.py` gets from the registry):

    check_motion_tables.py --mh4u build/mh4u.tsv \
        --source mh3u build/mh3u.tsv build/map-mh4u-mh3u.tsv \
        --source mhxx build/mhxx.tsv build/map-mh4u-mhxx.tsv

The signature fallback, mods/monster_motions/src/fallback.h (`reference/monster_motions.py
fallback`), is checked too: its generator's marker, one table per registered monster in id
order whose count is its entries', entries sorted by MH4U motion number and unique, no entry
that maps a number to itself, and both numbers a motion index (file 0 to 4, slot below 0x100).
With `--mh4u-romfs` and `--source-romfs`, it must be exactly what the generator writes.

Usage: check_motion_tables.py [--header PATH] [--fallback PATH] [--registry PATH]
           [--mh4u TSV --source GAME TSV MAP ...] [--mh4u-romfs PATH --source-romfs GAME PATH ...]
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "reference"))

import monster_motions  # noqa: E402

HEADER = os.path.join(ROOT, "mods", "monster_motions", "src", "motions.h")
FALLBACK = os.path.join(ROOT, "mods", "monster_motions", "src", "fallback.h")
FALLBACK_TABLE = re.compile(r"^static const MhucMotionFallback mhuc_fallback_(\d+)\[\] = \{$")
NO_FALLBACK = re.compile(r"^static const MhucMotionFallback \*const mhuc_fallback_(\d+) = NULL;$")
FALLBACK_ENTRY = re.compile(r"^    \{0x([0-9a-f]{3}), 0x([0-9a-f]{3})\},$")
FALLBACK_META = re.compile(r"^    \{(\d+), (\d+), mhuc_fallback_(\d+)\},$")
REGISTRY = os.path.join(ROOT, "data", "ids", "registry.csv")

# R1's last result (docs/checks.md#monster-actions): the MH4U/source pair's counts, and the
# number of compared ids the content comparison could not resolve. Source: R1's rerun on
# MH4U USA v1.3.0, MHXX v1.4 roEm001 and MH3U USA, 2026-11-24/25.
R1_COUNTS = {
    "mhxx": dict(common=273, compared=167, same_index=167, not_compared=106, unresolved=0),
    "mh3u": dict(common=174, compared=117, same_index=2, not_compared=57, unresolved=19),
}
GENERATED = f"Generated from R1's comparison by {monster_motions.GENERATOR}."

MOTIONS = re.compile(r"^static const MhucMotion mhuc_motions_(\d+)\[\] = \{$")
NO_MOTIONS = re.compile(r"^static const MhucMotion \*const mhuc_motions_(\d+) = NULL;$")
UNRESOLVED = re.compile(r"^static const uint16_t mhuc_unresolved_(\d+)\[\] = \{$")
NO_UNRESOLVED = re.compile(r"^static const uint16_t \*const mhuc_unresolved_(\d+) = NULL;$")
ENTRY = re.compile(r"^    \{(\d+), (\d+), (0x[0-9a-f]+), (0x[0-9a-f]+)\},$")
LEFT_OUT = re.compile(r"^    0x([0-9a-f]{4}), /\* (\d+(?:/\d+)?) \*/$")
META = re.compile(r"^    \{(\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), "
                  r"mhuc_motions_(\d+), mhuc_unresolved_(\d+)\},$")
COUNT = re.compile(r"^#define MHUC_PORTED_MOTIONS_COUNT (\d+)$")


def parse_header(text: str) -> dict:
    """The header's tables, meta rows and declared count.

    Only the generated lines are read: an array's entries and left-out ids, the meta rows and
    the count. The C declarations and comments around them are the generator's fixed text."""
    tables: dict[int, dict] = {}
    meta = []
    count = None
    current = None          # (kind, id) of the array being read
    for number, line in enumerate(text.splitlines(), start=1):
        if m := COUNT.match(line):
            count = int(m.group(1))
            continue
        if m := MOTIONS.match(line):
            current = ("entries", int(m.group(1)))
            tables.setdefault(current[1], dict(entries=[], unresolved=[]))
            continue
        if m := NO_MOTIONS.match(line):
            tables.setdefault(int(m.group(1)), dict(entries=[], unresolved=[]))
            current = None
            continue
        if m := UNRESOLVED.match(line):
            current = ("unresolved", int(m.group(1)))
            tables.setdefault(current[1], dict(entries=[], unresolved=[]))
            continue
        if m := NO_UNRESOLVED.match(line):
            tables.setdefault(int(m.group(1)), dict(entries=[], unresolved=[]))
            current = None
            continue
        if line == "};":
            current = None
            continue
        if current and (m := ENTRY.match(line)):
            if current[0] != "entries":
                raise ValueError(f"line {number}: an entry outside a motion array")
            tables[current[1]]["entries"].append(
                dict(category=int(m.group(1)), index=int(m.group(2)),
                     motion=int(m.group(3), 0), source=int(m.group(4), 0)))
            continue
        if current and (m := LEFT_OUT.match(line)):
            if current[0] != "unresolved":
                raise ValueError(f"line {number}: a left-out id outside its array")
            tables[current[1]]["unresolved"].append(int(m.group(1), 16))
            continue
        if m := META.match(line):
            meta.append(dict(id=int(m.group(1)), entry_count=int(m.group(2)),
                             unresolved_count=int(m.group(3)), common=int(m.group(4)),
                             compared=int(m.group(5)), same_index=int(m.group(6)),
                             not_compared=int(m.group(7)), motions=int(m.group(8)),
                             unresolved=m.group(9)))
            continue
    if count is None:
        raise ValueError("no MHUC_PORTED_MOTIONS_COUNT: the header is cut short")
    if "static const MhucPortedMotions mhuc_ported_motions[MHUC_PORTED_MOTIONS_COUNT]" not in text:
        raise ValueError("no mhuc_ported_motions table")
    return dict(tables=tables, meta=meta, count=count)


def check(text: str, registry: list[dict]) -> list[str]:
    """What is wrong with the generated header, against the registry and R1's counts."""
    problems: list[str] = []
    if not text.startswith(f"/* {GENERATED}"):
        problems.append(f"no generated marker: the header must start with /* {GENERATED}")
        return problems
    try:
        parsed = parse_header(text)
    except ValueError as e:
        return [str(e)]
    wanted = sorted(int(r["id"], 0) for r in registry)
    if parsed["count"] != len(parsed["meta"]):
        problems.append(f"the count says {parsed['count']} tables, the meta table has {len(parsed['meta'])}")
    if [m["id"] for m in parsed["meta"]] != wanted:
        problems.append(f"the meta table's ids {[m['id'] for m in parsed['meta']]} aren't the "
                        f"registry's ported monsters {wanted}")
    by_id = {int(r["id"], 0): r for r in registry}
    for m in parsed["meta"]:
        where = f"id {m['id']}"
        if m["motions"] != m["id"] or m["unresolved"] != str(m["id"]):
            problems.append(f"{where}: the meta row names another table ({m['motions']})")
        table = parsed["tables"].get(m["id"])
        if table is None:
            problems.append(f"{where}: no mhuc_motions_{m['id']} table")
            continue
        entries, out = table["entries"], table["unresolved"]
        where = f"id {m['id']} ({by_id.get(m['id'], {}).get('key', 'unregistered')})"
        if m["entry_count"] != len(entries):
            problems.append(f"{where}: entry_count {m['entry_count']} but {len(entries)} entries")
        if m["unresolved_count"] != len(out):
            problems.append(f"{where}: unresolved_count {m['unresolved_count']} but {len(out)} ids")
        problems += _check_entries(where, entries)
        problems += _check_left_out(where, out, entries)
        problems += _check_counts(where, m, by_id.get(m["id"]))
    return problems


def _check_entries(where: str, entries: list[dict]) -> list[str]:
    problems = []
    keys = []
    for e in entries:
        if not 0 <= e["category"] <= 255 or not 0 <= e["index"] <= monster_motions.NO_INDEX:
            problems.append(f"{where}: action {e['category']}/{e['index']} isn't two bytes")
        if not 0 < e["motion"] < monster_motions.MAX_MOTION:
            problems.append(f"{where}: motion 0x{e['motion']:x} is out of range")
        if not 0 < e["source"] < monster_motions.MAX_MOTION:
            problems.append(f"{where}: source 0x{e['source']:x} is out of range")
        keys.append((e["category"], e["index"], e["motion"]))
    if keys != sorted(keys):
        problems.append(f"{where}: the entries aren't sorted by action and motion")
    if len(keys) != len(set(keys)):
        problems.append(f"{where}: an action and motion appear twice")
    return problems


def _check_left_out(where: str, out: list[int], entries: list[dict]) -> list[str]:
    problems = []
    if out != sorted(out):
        problems.append(f"{where}: the left-out ids aren't sorted")
    if len(out) != len(set(out)):
        problems.append(f"{where}: a left-out id appears twice")
    have = {(e["category"], e["index"]) for e in entries}
    for value in out:
        cat, idx = value >> 8, value & 0xFF
        if cat != 7:
            problems.append(f"{where}: left-out id {cat}/{idx} isn't category 7's computed index")
        if (cat, idx) in have:
            problems.append(f"{where}: {cat}/{idx} is both translated and left out")
    return problems


def _check_counts(where: str, meta: dict, row: dict | None) -> list[str]:
    problems = []
    if meta["common"] != meta["compared"] + meta["not_compared"]:
        problems.append(f"{where}: common {meta['common']} isn't compared + not compared")
    if meta["entry_count"] + meta["same_index"] + meta["unresolved_count"] != meta["compared"]:
        problems.append(f"{where}: entries, same-index and left-out ids don't add up to "
                        f"compared {meta['compared']}")
    if row is None:
        return problems
    r1 = R1_COUNTS.get(row["source_game"])
    if r1 is None:
        problems.append(f"{where}: no R1 counts for source game {row['source_game']!r}; add them here")
        return problems
    for key in ("common", "compared", "same_index", "not_compared"):
        if meta[key] != r1[key]:
            problems.append(f"{where}: {key} {meta[key]} isn't R1's {r1[key]}")
    if meta["unresolved_count"] != r1["unresolved"]:
        problems.append(f"{where}: {meta['unresolved_count']} left-out ids isn't R1's {r1['unresolved']}")
    return problems


def check_fallback(text: str, registry: list[dict]) -> list[str]:
    """fallback.h's shape: see the module's docstring."""
    where = os.path.relpath(FALLBACK, ROOT)
    problems = []
    if f"by {monster_motions.FALLBACK_GENERATOR}." not in text.splitlines()[0]:
        problems.append(f"{where}: no generator marker on its first line")
    tables, metas, current = {}, [], None
    for line in text.splitlines():
        m = FALLBACK_TABLE.match(line)
        if m:
            current = tables.setdefault(int(m.group(1)), [])
            continue
        m = NO_FALLBACK.match(line)
        if m:
            tables.setdefault(int(m.group(1)), [])
            continue
        if line == "};":
            current = None
            continue
        m = FALLBACK_ENTRY.match(line)
        if m and current is not None:
            current.append((int(m.group(1), 16), int(m.group(2), 16)))
            continue
        m = FALLBACK_META.match(line)
        if m:
            metas.append((int(m.group(1)), int(m.group(2)), int(m.group(3))))
    ids = [int(row["id"], 0) for row in registry]
    if [m[0] for m in metas] != ids:
        problems.append(f"{where}: its tables {[m[0] for m in metas]} aren't the registry's ported "
                        f"monsters {ids}")
    for ident, count, named in metas:
        entries = tables.get(ident)
        if entries is None or named != ident:
            problems.append(f"{where}: id {ident}'s table is missing or misnamed")
            continue
        if count != len(entries):
            problems.append(f"{where}: id {ident} counts {count} entries but holds {len(entries)}")
        motions = [a for a, _ in entries]
        if motions != sorted(set(motions)):
            problems.append(f"{where}: id {ident}'s entries aren't sorted and unique by motion")
        for a, b in entries:
            if a == b:
                problems.append(f"{where}: id {ident} maps 0x{a:03x} to itself")
            if a >> 8 > 4 or b >> 8 > 4:
                problems.append(f"{where}: id {ident}: 0x{a:03x} -> 0x{b:03x} isn't in files 0 to 4")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--header", default=HEADER)
    ap.add_argument("--fallback", default=FALLBACK)
    ap.add_argument("--registry", default=REGISTRY)
    ap.add_argument("--mh4u-romfs", help="MH4U's RomFS, to regenerate fallback.h and compare")
    ap.add_argument("--source-romfs", nargs=2, action="append", metavar=("GAME", "ROMFS"),
                    help="a source game's RomFS; repeatable (needs --mh4u-romfs)")
    ap.add_argument("--mh4u", help="R1's MH4U inventory, to regenerate and compare")
    ap.add_argument("--source", nargs=3, action="append", metavar=("GAME", "INVENTORY", "MAPPING"),
                    help="a source game's R1 inventory and mapping; repeatable (needs --mh4u)")
    args = ap.parse_args(argv)
    if bool(args.mh4u) != bool(args.source):
        print("--mh4u and --source go together", file=sys.stderr)
        return 2
    registry = monster_motions.read_registry(args.registry)
    text = ""
    if os.path.exists(args.header):
        with open(args.header, encoding="utf-8") as f:
            text = f.read()
    problems = check(text, registry) if text else [f"{args.header}: no header"]
    if args.mh4u:
        sources = {game: (monster_motions.read_rows(inventory), monster_motions.read_mapping(mapping))
                   for game, inventory, mapping in args.source}
        tables = monster_motions.tables_from(registry, monster_motions.read_rows(args.mh4u), sources)
        if monster_motions.render_header(tables) != text:
            problems.append(f"{os.path.relpath(args.header, ROOT)} isn't what the generator "
                            "writes from these inputs: run reference/monster_motions.py table")
    fallback = ""
    if os.path.exists(args.fallback):
        with open(args.fallback, encoding="utf-8") as f:
            fallback = f.read()
    problems += check_fallback(fallback, registry) if fallback else [f"{args.fallback}: no header"]
    if args.mh4u_romfs:
        out = os.path.join(os.path.dirname(os.path.abspath(args.fallback)), ".fallback.check")
        try:
            monster_motions.cmd_fallback(argparse.Namespace(
                mh4u_romfs=args.mh4u_romfs, source_romfs=args.source_romfs or [],
                registry=args.registry, output=out))
            with open(out, encoding="utf-8") as f:
                if f.read() != fallback:
                    problems.append(f"{os.path.relpath(args.fallback, ROOT)} isn't what the generator "
                                    "writes from these RomFS: run reference/monster_motions.py fallback")
        finally:
            if os.path.exists(out):
                os.remove(out)
    if problems:
        for p in problems:
            print(p)
        print("the motion table is wrong; it is generated, never edited", file=sys.stderr)
        return 1
    ids = ", ".join(str(int(row["id"], 0)) for row in registry)
    print(f"motion table ok ({os.path.relpath(args.header, ROOT)}: {len(registry)} ported "
          f"monster(s), ids {ids})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
