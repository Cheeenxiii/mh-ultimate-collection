#!/usr/bin/env python3
"""Check the ported monsters' generated action-id map, mods/monster_actions/src/actions.h.

The header is generated by `reference/monster_handlers.py table` from the per-id table
`reference/monster_handlers.py targets -o` writes: one table per ported monster id, each entry
saying which MH4U action serves a source game action MH4U's monster class lacks. This tool
checks that the checked-in header is the one the generator writes and that it agrees with the
map recorded in reference/README.md.

Checked without the player's own dumps:

- the header carries the generator's marker and one table per monster in data/ids/registry.csv,
  in id order, with the tables' ids and counts;
- each table's entries are sorted, unique, and hold action numbers in range; an empty table is
  NULL with a count of 0; an entry does not map an action to itself;
- the recorded map belongs to the monster `reference/monster_handlers.py`'s `MAP_KEY` names
  (`rathian-3u`): its table maps exactly the ids MH4U lacks that reach a shared handler (the 16
  of #115), and every other registered monster's table is empty;
- the table's source ids and targets are the ones reference/README.md records, no more and no
  fewer.

With the per-id table, pass `--targets build/3u-targets.tsv`: the header must then be exactly
what the generator writes, and the page's targets must be the ones it picks.

Usage: check_action_map.py [--header PATH] [--registry PATH] [--page PATH] [--targets TSV]
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "reference"))

import monster_handlers  # noqa: E402

HEADER = os.path.join(ROOT, "mods", "monster_actions", "src", "actions.h")
REGISTRY = os.path.join(ROOT, "data", "ids", "registry.csv")
PAGE = os.path.join(ROOT, "reference", "README.md")

# The 16 ids #115 found that reach a shared handler, and the one it did not (action 4, #136).
MAPPED = {"0/4", "7/64", "7/87", "7/93", "10/0", "10/1", "10/2", "10/3", "10/4", "10/5",
          "10/6", "11/5", "11/15", "11/26", "11/28", "13/9"}

GENERATED = f"/* {monster_handlers.GENERATED}"
COUNT = re.compile(r"^#define MHUC_PORTED_ACTIONS_COUNT (\d+)$")
ARRAY = re.compile(r"^static const MhucAction mhuc_actions_(\d+)\[\] = \{$")
NO_ARRAY = re.compile(r"^static const MhucAction \*const mhuc_actions_(\d+) = NULL;$")
ENTRY = re.compile(r"^    \{(\d+), (\d+), (\d+), (\d+)\},$")
META = re.compile(r"^    \{(\d+), (\d+), mhuc_actions_(\d+)\},$")
PAGE_HEADING = "### The 17 ids MH4U has no action for"
PAGE_ROW = re.compile(r"^\| ([\d/]+) \| ([\d/]+) \|")


def parse_header(text: str) -> dict:
    """The header's tables, meta rows and declared count, from its generated lines."""
    tables: dict[int, dict] = {}
    meta = []
    count = None
    current = None
    for line in text.splitlines():
        if m := COUNT.match(line):
            count = int(m.group(1))
            continue
        if m := ARRAY.match(line):
            current = int(m.group(1))
            tables[current] = []
            continue
        if m := NO_ARRAY.match(line):
            current = None
            tables.setdefault(int(m.group(1)), [])
            continue
        if line == "};":
            current = None
            continue
        if current is not None and (m := ENTRY.match(line)):
            tables[current].append(dict(category=int(m.group(1)), index=int(m.group(2)),
                                        target_category=int(m.group(3)),
                                        target_index=int(m.group(4))))
            continue
        if m := META.match(line):
            meta.append(dict(id=int(m.group(1)), entry_count=int(m.group(2)),
                             array=int(m.group(3))))
            continue
    if count is None:
        raise ValueError("no MHUC_PORTED_ACTIONS_COUNT: the header is cut short")
    if "static const MhucPortedActions mhuc_ported_actions[MHUC_PORTED_ACTIONS_COUNT]" not in text:
        raise ValueError("no mhuc_ported_actions table")
    return dict(tables=tables, meta=meta, count=count)


def read_page(path: str = PAGE) -> dict[str, str]:
    """reference/README.md's per-id map: source action -> the action the map runs."""
    rows = {}
    inside = False
    for line in open(path, encoding="utf-8"):
        if line.startswith("### "):
            inside = line.startswith(PAGE_HEADING)
            continue
        if inside and (m := PAGE_ROW.match(line)):
            rows[m.group(1)] = m.group(2)
    return rows


def action_key(category: int, index: int) -> str:
    """An action as the page names it: index 0xff is a category-only action's wildcard."""
    return monster_handlers.action_id(
        (category, None if index == monster_handlers.NO_INDEX else index))


def check(text: str, registry: list[dict[str, str]], page: dict[str, str]) -> list[str]:
    """What is wrong with the generated header, against the registry and the page."""
    problems: list[str] = []
    if not text.startswith(GENERATED):
        return [f"no generated marker: the header must start with {GENERATED}"]
    try:
        parsed = parse_header(text)
    except ValueError as error:
        return [str(error)]
    ids = [int(r["id"]) for r in registry]
    if parsed["count"] != len(ids):
        problems.append(f"MHUC_PORTED_ACTIONS_COUNT is {parsed['count']}, the registry has "
                        f"{len(ids)} monster(s)")
    meta_ids = [row["id"] for row in parsed["meta"]]
    if meta_ids != sorted(ids):
        problems.append(f"the meta table's ids are {meta_ids}, the registry's are {sorted(ids)}")
    if set(parsed["tables"]) != set(ids):
        problems.append(f"the tables' ids are {sorted(parsed['tables'])}, the registry's are "
                        f"{sorted(ids)}")
    for row in parsed["meta"]:
        mid = row["id"]
        entries = parsed["tables"].get(mid, [])
        if row["entry_count"] != len(entries):
            problems.append(f"id {mid}: entry_count is {row['entry_count']}, the table holds "
                            f"{len(entries)}")
        if row["array"] != mid:
            problems.append(f"id {mid}: the meta row points at mhuc_actions_{row['array']}")
        keys = [(e["category"], e["index"]) for e in entries]
        if keys != sorted(keys):
            problems.append(f"id {mid}: the entries are not sorted by category and index")
        if len(keys) != len(set(keys)):
            problems.append(f"id {mid}: a source action appears twice")
        for e in entries:
            for field in ("category", "index", "target_category", "target_index"):
                if not 0 <= e[field] <= 0xFF:
                    problems.append(f"id {mid}: {field} {e[field]} is outside one byte")
            if (e["category"], e["index"]) == (e["target_category"], e["target_index"]):
                problems.append(f"id {mid}: {e['category']}/{e['index']} maps to itself")
        if not entries:
            if f"static const MhucAction *const mhuc_actions_{mid} = NULL;" not in text:
                problems.append(f"id {mid}: an empty table must be NULL")

    owner = next((r for r in registry if r["key"] == monster_handlers.MAP_KEY), None)
    if owner is None:
        problems.append(f"the registry has no {monster_handlers.MAP_KEY} row, the monster whose "
                        "action-id map is recorded")
        return problems
    ported = int(owner["id"])
    for mid in sorted(ids):
        if mid != ported and parsed["tables"].get(mid):
            problems.append(f"id {mid}: {monster_handlers.MAP_KEY}'s is the only recorded map; "
                            "every other monster's table must be empty")
    entries = parsed["tables"].get(ported, [])
    header_map = {action_key(e["category"], e["index"]):
                  action_key(e["target_category"], e["target_index"])
                  for e in entries}
    if set(header_map) != MAPPED:
        problems.append(f"id {ported}: the mapped ids are {sorted(header_map)}, not the 16 of "
                        f"#115: {sorted(MAPPED)}")
    if "4" in header_map:
        problems.append("action 4 needs new C (#136) and must not be in the map")
    if header_map != page:
        missing = sorted(set(page) - set(header_map))
        extra = sorted(set(header_map) - set(page))
        differ = sorted(k for k in set(header_map) & set(page) if header_map[k] != page[k])
        problems.append(f"the header and reference/README.md's map differ: missing {missing}, "
                        f"extra {extra}, different target {differ}")
    return problems


def check_generator(text: str, targets: str, registry: list[dict[str, str]]) -> list[str]:
    """The header must be exactly what `monster_handlers.py table` writes from the per-id table."""
    mapped, _ = monster_handlers.build_map(
        monster_handlers.read_targets(targets),
        [monster_handlers.parse_action(x) for x in sorted(MAPPED)])
    expected = monster_handlers.render_header(mapped, registry)
    if text != expected:
        return ["the header is not what reference/monster_handlers.py table writes from "
                f"{targets}: run it again"]
    return []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--header", default=HEADER)
    ap.add_argument("--registry", default=REGISTRY)
    ap.add_argument("--page", default=PAGE)
    ap.add_argument("--targets", help="the `targets -o` per-id table, for the exact re-render")
    args = ap.parse_args(argv)
    text = open(args.header, encoding="utf-8").read()
    registry = monster_handlers.read_registry(args.registry)
    problems = check(text, registry, read_page(args.page))
    if args.targets:
        problems += check_generator(text, args.targets, registry)
    for problem in problems:
        print(f"action map: {problem}")
    if problems:
        return 1
    entries = sum(len(t) for t in parse_header(text)["tables"].values())
    print(f"action map ok: {entries} entries, {len(registry)} ported monster(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
